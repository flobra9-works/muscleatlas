/* Turns the raw Blender output in drafts/render/ into the assets the app ships.
 *
 *   node scripts/build-bodyplates.js
 *
 * Beauty plates  -> assets/body/{front,back}.webp   (what you see)
 * Region maps    -> assets/body/{front,back}-id.png (what you click)
 *
 * The id map is a lookup image, not a picture: its red channel holds the region
 * index (index * 12). The app reads the pixel under your finger to know which
 * muscle was hit, and recolours the same map to draw the activation heatmap.
 * That is why it must stay lossless PNG and must never be resampled with a
 * smoothing filter — nearest-neighbour only, or the indices blend into
 * neighbouring regions and produce phantom hits.
 *
 * Source artwork: Z-Anatomy (CC BY-SA 4.0), derived from BodyParts3D
 * (CC BY-SA 2.1 Japan). Rendered output is a derivative work under CC BY-SA 4.0.
 */

const sharp = require('sharp');
const fs = require('fs');
const path = require('path');

const VON = path.join(__dirname, '..', 'drafts', 'render');
const NACH = path.join(__dirname, '..', 'assets', 'body');
const SCHRITT = 12;                 // must match SCHRITT in scripts/za-regions.py
const ID_HOEHE = 1350;              // id map resolution — finer than finger precision

fs.mkdirSync(NACH, { recursive: true });

async function beauty(name) {
  const quelle = path.join(VON, name + '.png');
  const ziel = path.join(NACH, name + '.webp');
  const info = await sharp(quelle)
    .webp({ quality: 88, alphaQuality: 90, effort: 6 })
    .toFile(ziel);
  const vorher = fs.statSync(quelle).size;
  console.log(`  ${name}.webp  ${info.width}x${info.height}  ` +
    `${(info.size / 1024).toFixed(0)} KB  (from ${(vorher / 1024).toFixed(0)} KB PNG)`);
}

async function idmap(name) {
  const quelle = path.join(VON, name + '.png');
  const ziel = path.join(NACH, name + '.png');

  // Nearest-neighbour only: interpolation would invent indices between regions.
  const bild = sharp(quelle).resize({ height: ID_HOEHE, kernel: 'nearest' });
  const { data, info } = await bild.raw().toBuffer({ resolveWithObject: true });

  // Snap every pixel to an exact index colour. Blender leaves a one-value fringe
  // along region borders; snapping removes it, which both fixes stray hits and
  // lets the PNG compress properly (flat colour areas instead of noise).
  const kanaele = info.channels;
  const histogramm = new Map();
  for (let i = 0; i < data.length; i += kanaele) {
    const a = kanaele === 4 ? data[i + 3] : 255;
    if (a < 128) { data[i] = data[i + 1] = data[i + 2] = 0; if (kanaele === 4) data[i + 3] = 0; continue; }
    const idx = Math.round(data[i] / SCHRITT);
    const wert = idx * SCHRITT;
    data[i] = wert; data[i + 1] = 0; data[i + 2] = 0;
    if (kanaele === 4) data[i + 3] = 255;
    histogramm.set(idx, (histogramm.get(idx) || 0) + 1);
  }

  const info2 = await sharp(data, { raw: { width: info.width, height: info.height, channels: kanaele } })
    .png({ compressionLevel: 9, palette: true, colours: 32 })
    .toFile(ziel);

  const vorher = fs.statSync(quelle).size;
  console.log(`  ${name}.png   ${info2.width}x${info2.height}  ` +
    `${(info2.size / 1024).toFixed(0)} KB  (from ${(vorher / 1024).toFixed(0)} KB)  ` +
    `regions present: ${[...histogramm.keys()].filter(k => k > 0).length}`);
  return histogramm;
}

// The app has to decode red channel -> region id exactly the way the renderer
// encoded it. Rather than keep two hand-written lists in sync, derive the app's
// list from scripts/za-regions.py, which stays the single source of truth.
function schreibeRegionen() {
  const py = fs.readFileSync(path.join(__dirname, 'za-regions.py'), 'utf8');
  const start = py.indexOf('REGIONEN = [');
  const block = py.slice(start, py.indexOf('\n]', start));
  const ids = [...block.matchAll(/^\s*\("([a-z-]+)",/gm)].map(m => m[1]);
  if (!ids.length) throw new Error('could not parse REGIONEN from za-regions.py');

  const zeilen = [
    '/* GENERATED by scripts/build-bodyplates.js — do not edit by hand.',
    '   The order defines the region index encoded in the body id maps',
    '   (red channel = index * ' + SCHRITT + '). Source: scripts/za-regions.py */',
    '',
    'const BODY_REGIONEN = [',
    ids.map(id => "  '" + id + "'").join(',\n'),
    '];',
    'const BODY_ID_SCHRITT = ' + SCHRITT + ';',
    ''
  ];
  fs.writeFileSync(path.join(__dirname, '..', 'data', 'bodyregions.js'),
    zeilen.join('\n'));
  console.log('  data/bodyregions.js  ' + ids.length + ' regions');
  return ids;
}

(async () => {
  console.log('Region order:');
  schreibeRegionen();
  console.log('Body plates:');
  await beauty('front');
  await beauty('back');
  console.log('Region maps:');
  const h1 = await idmap('front-id');
  const h2 = await idmap('back-id');

  const alle = new Set([...h1.keys(), ...h2.keys()].filter(k => k > 0));
  console.log(`\n${alle.size} of 20 regions visible across both views.`);

  const gesamt = ['front.webp', 'back.webp', 'front-id.png', 'back-id.png']
    .reduce((s, f) => s + fs.statSync(path.join(NACH, f)).size, 0);
  console.log(`Total shipped: ${(gesamt / 1024).toFixed(0)} KB`);
})().catch(e => { console.error(e); process.exit(1); });

